/**
 * Regenerates src/db/embedded-migrations.ts from the drizzle/ folder.
 * Runs automatically as part of `bun run db:generate`.
 */
import { Glob } from "bun";
import { basename } from "node:path";

const DRIZZLE_DIR = "./drizzle";
const OUT_FILE = "./src/db/embedded-migrations.ts";

const files = (await Array.fromAsync(new Glob("*.sql").scan(DRIZZLE_DIR))).sort();
if (files.length === 0) {
  console.error("No .sql files in ./drizzle — run drizzle-kit generate first");
  process.exit(1);
}

const imports = files.map((f, i) => `import m${i} from "../../drizzle/${f}" with { type: "text" };`).join("\n");
const entries = files.map((f, i) => `  { name: "${basename(f, ".sql")}", sql: m${i} },`).join("\n");

await Bun.write(
  OUT_FILE,
  `/**
 * SQL migrations embedded via Bun import attributes.
 *
 * Auto-generated by: bun run db:generate — do not edit.
 */
${imports}

export const EMBEDDED_MIGRATIONS: Array<{ name: string; sql: string }> = [
${entries}
];
`,
);
console.log(`✅ Embedded ${files.length} migration(s) into ${OUT_FILE}`);
